'use strict';

const { contextBridge, ipcRenderer, webUtils } = require('electron');

async function invoke(channel, ...values) {
  const result = await ipcRenderer.invoke(channel, ...values);
  if (!result.ok) throw new Error(result.error);
  return result.value;
}

